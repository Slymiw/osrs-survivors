package com.osrssurvivors;

import com.google.gson.Gson;
import com.osrssurvivors.audio.SynthSound;
import java.io.DataOutputStream;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.Base64;
import java.util.Map;
import java.util.TreeMap;
import net.runelite.cache.IndexType;
import net.runelite.cache.fs.Archive;
import net.runelite.cache.fs.FSFile;
import net.runelite.cache.fs.Index;
import net.runelite.cache.fs.Storage;
import net.runelite.cache.fs.Store;

/**
 * Exports the game's sound effects ({@link SoundTable}) from a local OSRS cache into
 * {@code assets/sounds.js}: the table of keys to sound ids, Jagex's name for each sound, and each
 * sound's cache file as it is (a few hundred bytes of synthesiser settings, which the page turns
 * into samples itself with {@link SynthSound}). Every sound is decoded here first, so a broken
 * file stops the export instead of failing quietly in the browser.
 *
 * <p>With a third argument, also writes each sound as a WAV file into that directory, to listen
 * to or inspect.
 */
public final class SoundExport
{
	private SoundExport()
	{
	}

	public static void main(String[] args) throws IOException
	{
		if (args.length < 2)
		{
			System.err.println("usage: SoundExport <OSRS cache directory> <output directory> [wav directory]");
			System.exit(2);
		}
		File cacheDir = new File(args[0]);
		if (!new File(cacheDir, "main_file_cache.dat2").isFile())
		{
			System.err.println("No OSRS cache in " + cacheDir + ". Run the game client once, or pass -PcacheDir=<dir>.");
			System.exit(1);
		}
		File wavDir = args.length > 2 ? new File(args[2]) : null;
		Map<String, SoundTable.Sfx> table = SoundTable.build();
		Map<String, Integer> keys = new TreeMap<>();
		Map<String, String> names = new TreeMap<>();
		Map<String, String> data = new TreeMap<>();
		int bytes = 0;
		try (Store store = new Store(cacheDir))
		{
			store.load();
			Storage storage = store.getStorage();
			Index sounds = store.getIndex(IndexType.SOUNDEFFECTS);
			for (Map.Entry<String, SoundTable.Sfx> e : table.entrySet())
			{
				SoundTable.Sfx sfx = e.getValue();
				keys.put(e.getKey(), sfx.id);
				String id = String.valueOf(sfx.id);
				if (data.containsKey(id))
				{
					continue;
				}
				Archive archive = sounds.getArchive(sfx.id);
				if (archive == null)
				{
					throw new IOException("sound " + sfx.id + " (" + sfx.name + ") is not in the cache");
				}
				byte[] raw = null;
				for (FSFile f : archive.getFiles(storage.loadArchive(archive)).getFiles())
				{
					raw = f.getContents();
				}
				float[] pcm = SynthSound.decode(raw).mix();
				if (pcm.length == 0)
				{
					throw new IOException("sound " + sfx.id + " (" + sfx.name + ") is silent");
				}
				names.put(id, sfx.name);
				data.put(id, Base64.getEncoder().encodeToString(raw));
				bytes += raw.length;
				if (wavDir != null)
				{
					writeWav(new File(wavDir, sfx.id + "_" + sfx.name + ".wav"), pcm);
				}
			}
		}
		Gson gson = new Gson();
		StringBuilder js = new StringBuilder();
		js.append("// Generated by SoundExport from the OSRS cache: the game's sound effects, as the client's own synthesiser\n");
		js.append("// settings (see SynthSound). Old School RuneScape and its sounds are the property of Jagex Ltd.\n");
		js.append("window.OSRS_SOUNDS = {\n");
		js.append("table: ").append(gson.toJson(keys)).append(",\n");
		js.append("names: ").append(gson.toJson(names)).append(",\n");
		js.append("data: ").append(gson.toJson(data)).append("\n");
		js.append("};\n");
		File out = new File(args[1], "sounds.js");
		Files.write(out.toPath(), js.toString().getBytes(StandardCharsets.UTF_8));
		System.out.println("Exported " + data.size() + " sounds (" + bytes + " bytes) for " + keys.size() + " keys to " + out);
	}

	private static void writeWav(File file, float[] pcm) throws IOException
	{
		file.getParentFile().mkdirs();
		try (DataOutputStream o = new DataOutputStream(new FileOutputStream(file)))
		{
			int n = pcm.length;
			o.writeBytes("RIFF");
			o.writeInt(Integer.reverseBytes(36 + n * 2));
			o.writeBytes("WAVEfmt ");
			o.writeInt(Integer.reverseBytes(16));
			o.writeShort(Short.reverseBytes((short) 1));
			o.writeShort(Short.reverseBytes((short) 1));
			o.writeInt(Integer.reverseBytes(SynthSound.SAMPLE_RATE));
			o.writeInt(Integer.reverseBytes(SynthSound.SAMPLE_RATE * 2));
			o.writeShort(Short.reverseBytes((short) 2));
			o.writeShort(Short.reverseBytes((short) 16));
			o.writeBytes("data");
			o.writeInt(Integer.reverseBytes(n * 2));
			for (float f : pcm)
			{
				o.writeShort(Short.reverseBytes((short) Math.max(-32768, Math.min(32767, Math.round(f * 32767)))));
			}
		}
	}
}
